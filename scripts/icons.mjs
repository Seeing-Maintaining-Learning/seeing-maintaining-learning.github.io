// Regenerate src/data/icons.ts from lucide-static (ISC). Run: node scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const MAP = {
  image: 'image', video_streaming: 'clapperboard', audio_speech: 'audio-lines', gui: 'mouse-pointer-click', embodied_3d: 'bot',
  T1: 'snowflake', T2: 'refresh-cw', T3: 'sparkles',
  source_preserving_and_modality_native_memory: 'scan-eye', cross_represented_explicit_memory: 'file-text',
  internalized_latent_and_parametric_memory: 'brain', hybrid: 'layers',
};
const out = {};
for (const [k, name] of Object.entries(MAP)) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  out[k] = svg.replace(/<!--.*?-->/s, '').replace(/^[\s\S]*?<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
writeFileSync(
  'src/data/icons.ts',
  `/** Line icons from Lucide (https://lucide.dev), ISC License. Generated by scripts/icons.mjs. */\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(Object.keys(out).length, 'icons');

// Also emit src/styles/icons.css: modality and tier markers show their icon (CSS mask) instead of a plain dot.
// Selectors are direct-child only so nested modality/tier containers never override each other.
const KEYS = [
  ...['image', 'video_streaming', 'audio_speech', 'gui', 'embodied_3d'].map((m) => [m, `mod-${m}`]),
  ...['T1', 'T2', 'T3'].map((t) => [t, `tier-${t}`]),
];
const sel = (c) => [
  `.chip.${c} > .dot`, `.${c} > .chip > .dot`, `.${c} > dd > .chip > .dot`, `.${c} > .dot`,
  `.${c} > .sw`, `.${c} > .swatch`, `.${c} > .tname > .dot`, `.legend .${c} > .dot`,
];
const css = KEYS.map(([k, c]) => {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2.2' stroke-linecap='round' stroke-linejoin='round'>${out[k].replace(/"/g, "'")}</svg>`;
  const uri = `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
  return `${sel(c).join(',\n')} {\n  -webkit-mask: ${uri} center / contain no-repeat;\n  mask: ${uri} center / contain no-repeat;\n}`;
}).join('\n');
const all = KEYS.flatMap(([, c]) => sel(c).filter((x) => !x.endsWith('.swatch')));
writeFileSync(
  'src/styles/icons.css',
  `/* Generated by scripts/icons.mjs: Lucide icons (ISC) as masks for modality and tier markers. */\n${css}\n` +
    `:is(${all.join(', ')}) {\n  width: 13px;\n  height: 13px;\n  border-radius: 0;\n  box-shadow: none;\n  background: var(--c);\n}\n`,
);
